import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { createPublicClient, createWalletClient, defineChain, encodeDeployData, formatEther, formatUnits, http, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { rateLimitedHttp } from "../src/lib/rpc";
import { StockBackClient, type QuoteAssetConfig } from "../src/lib/stockback";
import { curveLauncherAbi, curveMarketAbi, memeAbi, stockAbi, marketAbi } from "../src/lib/abis";
import { curveLaunchOutput, optionalUnits } from "../src/lib/launch";

const live = process.argv.includes("--testnet");
const rpc = live ? "https://testnet-rpc.monad.xyz" : "http://127.0.0.1:8546";
const chain = defineChain({ id: live ? 10143 : 31337, name: live ? "Monad Testnet" : "Local", nativeCurrency: { name: "Monad", symbol: "MON", decimals: 18 }, rpcUrls: { default: { http: [rpc] } }, testnet: true });
const client = createPublicClient({ chain, pollingInterval: live ? 1000 : 50, transport: live ? rateLimitedHttp(rpc) : http(rpc) });
assert.equal(await client.getChainId(), chain.id);
const account = live ? privateKeyToAccount(process.env.DEPLOYER_PRIVATE_KEY as Hex) : (await createWalletClient({ transport: http(rpc) }).getAddresses())[8];
const wallet = createWalletClient({ account, chain, transport: live ? rateLimitedHttp(rpc) : http(rpc) });
const address = typeof account === "string" ? account : account.address;
if (live) assert.equal(address.toLowerCase(), "0x7640dfae2c612aba5567477aaa91b181f6de1a7c");
const root = new URL("../../", import.meta.url);
const catalog = JSON.parse(await readFile(new URL(live ? "shared/assets.json" : "shared/asset-local.json", root), "utf8")) as { chainId: number; assets: QuoteAssetConfig[] };
assert.equal(catalog.chainId, chain.id);
const configPath = new URL(live ? "shared/launcher.json" : "shared/launcher.local.json", root);
const previous = JSON.parse(await readFile(configPath, "utf8"));
if (previous.model === "bonding-curve") throw new Error("Bonding curve launcher is already configured; refusing duplicate deployment.");
const legacyLaunchers = [previous.address, ...(previous.legacyLaunchers ?? [])].filter(Boolean);
const artifact = JSON.parse(await readFile(new URL("contracts/out/BondingCurveLauncher.sol/BondingCurveLauncher.json", root), "utf8"));
const rewardArtifact = JSON.parse(await readFile(new URL("contracts/out/BondingCurveFactory.sol/BondingCurveFactory.json", root), "utf8"));
const rewardGas = await client.estimateGas({ account: address, data: encodeDeployData({ abi: rewardArtifact.abi, bytecode: rewardArtifact.bytecode.object, args: [address] }) });
// Include a conservative launcher allowance before broadcasting the factory.
const combinedBudget = (rewardGas + 2_500_000n) * (await client.getGasPrice()) * 12n / 10n;
assert.ok(await client.getBalance({ address }) > combinedBudget, "Additional test MON required before deploying launch contracts.");
console.log("Combined launch deployment budget MON", formatEther(combinedBudget), "Available MON", formatEther(await client.getBalance({ address })));
if (process.argv.includes("--check")) process.exit(0);
const rewardHash = await wallet.deployContract({ abi: rewardArtifact.abi, bytecode: rewardArtifact.bytecode.object, args: [address] });
const rewardReceipt = await client.waitForTransactionReceipt({ hash: rewardHash });
assert.equal(rewardReceipt.status, "success");
const rewardFactory = rewardReceipt.contractAddress!;
const args = [catalog.assets.map(a => a.factory), rewardFactory];
const gas = await client.estimateGas({ account: address, data: encodeDeployData({ abi: artifact.abi, bytecode: artifact.bytecode.object, args }) });
const budget = gas * (await client.getGasPrice()) * 12n / 10n;
assert.ok(await client.getBalance({ address }) > budget, "Additional test MON required.");
console.log("Launcher deployment budget MON", formatEther(budget));
const hash = await wallet.deployContract({ abi: artifact.abi, bytecode: artifact.bytecode.object, args });
const receipt = await client.waitForTransactionReceipt({ hash });
assert.equal(receipt.status, "success");
const launcher = receipt.contractAddress!;
await writeFile(new URL(live ? "shared/launcher.json" : "shared/launcher.local.json", root), JSON.stringify({ chainId: chain.id, model: "bonding-curve", virtualQuoteReserve: "1000", legacyLaunchers, address: launcher, hash, rewardFactory, rewardFactoryHash: rewardHash, treasury: address, factories: args[0] }, null, 2) + "\n");
console.log("Launcher", launcher, "transaction", hash);
for (const asset of catalog.assets) assert.equal((await client.readContract({ address: launcher, abi: curveLauncherAbi, functionName: "factoryFor", args: [asset.id] })).toLowerCase(), asset.factory.toLowerCase());
if (!live) {
  const asset = catalog.assets[1];
  const service = new StockBackClient(client, chain, asset.id, asset.factory, async () => wallet, undefined, catalog.assets, launcher, legacyLaunchers, true);
  const before = await service.snapshot(address);
  const legacyCount = before.markets.length;
  assert.equal(before.wallet.stockBalance, "0");
  await service.launchCurveCoin({name: "Zero funding launch", symbol: "ZERO", stockTokenId: asset.id, devBuyAmount: "0", tradingFeeBps: 100, metadata: {website:"https://example.com"}});
  const zero = (await service.snapshot(address)).markets.find(m => m.token.symbol === "ZERO")!;
  assert.ok(zero.bondingCurve);
  assert.equal(zero.stockReserve,"0");
  assert.ok(optionalUnits(zero.estimatedPrice!) > 0n);
  assert.equal(await client.readContract({address: asset.id, abi: stockAbi, functionName:"balanceOf", args:[address]}), 0n);
  assert.equal(await client.readContract({address: asset.id, abi: stockAbi, functionName:"allowance", args:[address, launcher]}), 0n);
  await service.faucet();
  for (const feeBps of [100, 300] as const) {
    const ticker = feeBps === 100 ? "CURVEONE" : "CURVETHREE";
    await service.launchCurveCoin({name:"Curve demo", symbol:ticker, stockTokenId:asset.id, devBuyAmount:"100", tradingFeeBps:feeBps, metadata:{website:"https://example.com"}});
    const snapshot = await service.snapshot(address);
    const market = snapshot.markets.find(m => m.token.symbol === ticker)!;
    assert.equal(market.tradingFeeBps,feeBps);
    assert.ok(market.bondingCurve);
    assert.equal(market.stockReserve,feeBps===100 ? "99" : "97");
    const minted = await client.readContract({address:market.token.id as Hex, abi:memeAbi, functionName:"balanceOf", args:[address]});
    assert.equal(minted, curveLaunchOutput(optionalUnits("100"),feeBps));
    const buyRequest = {marketId:market.id,side:"buy" as const,amount:"10",slippageBps:50};
    await service.approve(asset.id,market.id as Hex,"10");
    const buyQuote = await service.quote(buyRequest);
    assert.equal(buyQuote.feeAmount,feeBps===100 ? "0.1" : "0.3");
    await service.trade({...buyRequest,quoteId:buyQuote.id,minimumOutput:buyQuote.minimumOutput!});
    const held = await client.readContract({address:market.token.id as Hex,abi:memeAbi,functionName:"balanceOf",args:[address]});
    const amount = formatUnits(held/2n,18);
    await service.approve(market.token.id as Hex, market.id as Hex, amount);
    const request = {marketId:market.id,side:"sell" as const,amount,slippageBps:50};
    const q = await service.quote(request);
    const balanceBefore = await client.readContract({address:asset.id,abi:stockAbi,functionName:"balanceOf",args:[address]});
    await service.trade({...request,quoteId:q.id,minimumOutput:q.minimumOutput!});
    const balanceAfter = await client.readContract({address:asset.id,abi:stockAbi,functionName:"balanceOf",args:[address]});
    assert.equal(balanceAfter-balanceBefore,optionalUnits(q.outputAmount!));
    assert.ok(await client.readContract({address:market.id as Hex,abi:curveMarketAbi,functionName:"VIRTUAL_QUOTE_RESERVE"})>0n);
  }
  const final = await service.snapshot(address);
  assert.equal(final.markets.length, legacyCount+3);
  assert.equal(final.markets.filter(m=>!m.bondingCurve).length,legacyCount);
  console.log("PASS: zero-token launch without approval, both fees, curve buys/sells, real backing, metadata and legacy market preservation.");
}
