import assert from "node:assert/strict";
import {readFile,writeFile} from "node:fs/promises";
import {createPublicClient,createWalletClient,defineChain,encodeDeployData,formatEther,formatUnits,http,parseEther,type Address,type Hex} from "viem";
import {privateKeyToAccount} from "viem/accounts";
import {rateLimitedHttp} from "../src/lib/rpc";
import {StockBackClient,type QuoteAssetConfig} from "../src/lib/stockback";
import {nativeRouterAbi,memeAbi,stockAbi} from "../src/lib/abis";

const live=process.argv.includes("--testnet");
const rpc=live?"https://testnet-rpc.monad.xyz":"http://127.0.0.1:8546";
const chain=defineChain({id:live?10143:31337,name:live?"Monad Testnet":"Local",nativeCurrency:{name:"Monad",symbol:"MON",decimals:18},rpcUrls:{default:{http:[rpc]}},testnet:true});
const client=createPublicClient({chain,pollingInterval:live?1000:50,transport:live?rateLimitedHttp(rpc):http(rpc)});
assert.equal(await client.getChainId(),chain.id);
const account=live?privateKeyToAccount(process.env.DEPLOYER_PRIVATE_KEY as Hex):(await createWalletClient({transport:http(rpc)}).getAddresses())[7];
const address=typeof account==="string"?account:account.address;
if(live) assert.equal(address.toLowerCase(),"0x7640dfae2c612aba5567477aaa91b181f6de1a7c");
const wallet=createWalletClient({account,chain,transport:live?rateLimitedHttp(rpc):http(rpc)});
const root=new URL("../../",import.meta.url);
const deployment=JSON.parse(await readFile(new URL(live?"shared/launcher.json":"shared/launcher.local.json",root),"utf8"));
const assets=(JSON.parse(await readFile(new URL(live?"shared/assets.json":"shared/asset-local.json",root),"utf8")) as {assets:QuoteAssetConfig[]}).assets;
const configPath=new URL(live?"shared/native-router.json":"shared/native-router.local.json",root);
const existing=await readFile(configPath,"utf8").then(JSON.parse).catch(()=>null);
if(live && existing?.address) throw new Error("Native router already configured; refusing duplicate deployment.");
assert.equal(deployment.model,"bonding-curve");
const artifact=JSON.parse(await readFile(new URL("contracts/out/NativeRouter.sol/NativeRouter.json",root),"utf8"));
const args=[deployment.address,deployment.legacyLaunchers??[]];
const gas=await client.estimateGas({account:address,data:encodeDeployData({abi:artifact.abi,bytecode:artifact.bytecode.object,args})});
const budget=(gas+BigInt(assets.length)*150_000n)*(await client.getGasPrice())*115n/100n;
console.log("Router and conversion-reserve budget MON",formatEther(budget),"Available MON",formatEther(await client.getBalance({address})));
assert.ok(await client.getBalance({address})>budget,"Additional test MON required before deployment and reserve initialization.");
if(process.argv.includes("--check")) process.exit(0);
const hash=await wallet.deployContract({abi:artifact.abi,bytecode:artifact.bytecode.object,args});
const receipt=await client.waitForTransactionReceipt({hash});assert.equal(receipt.status,"success");
const router=receipt.contractAddress!;
const config={chainId:chain.id,address:router,quotePerMON:"1000",launcher:deployment.address,legacyLaunchers:deployment.legacyLaunchers??[],hash,seeds:[] as {symbol:string;hash:Hex}[]};
await writeFile(configPath,JSON.stringify(config,null,2)+"\n");
assert.equal(await client.readContract({address:router,abi:nativeRouterAbi,functionName:"QUOTE_PER_MON"}),1000n);
for(const asset of assets){
 const simulation=await client.simulateContract({address:router,abi:nativeRouterAbi,functionName:"seedQuote",args:[asset.id],account});
 const hash=await wallet.writeContract({...simulation.request,account,chain});
 assert.equal((await client.waitForTransactionReceipt({hash})).status,"success");
 assert.equal(await client.readContract({address:asset.id,abi:stockAbi,functionName:"balanceOf",args:[router]}),parseEther("10000"));
 config.seeds.push({symbol:asset.symbol,hash});await writeFile(configPath,JSON.stringify(config,null,2)+"\n");
}
console.log("Native router deployed and quote reserves initialized",router);
if(!live){
 const asset=assets[1];
 const service=new StockBackClient(client,chain,asset.id,asset.factory,async()=>wallet,undefined,assets,deployment.address,deployment.legacyLaunchers??[],true,router);
 assert.equal(await client.readContract({address:asset.id,abi:stockAbi,functionName:"balanceOf",args:[address]}),0n);
 await service.launchCurveCoin({name:"Native route demo",symbol:"MONDEMO",stockTokenId:asset.id,devBuyAmount:"0",tradingFeeBps:300,metadata:{}});
 const market=(await service.snapshot(address)).markets.find(m=>m.token.symbol==="MONDEMO")!;
 const buy={marketId:market.id,side:"buy" as const,paymentAsset:"native" as const,amountMode:"input" as const,amount:"0.1",slippageBps:50};
 let quote=await service.quote(buy);assert.equal(quote.feeAmount,"3");
 await service.trade({...buy,quoteId:quote.id,minimumOutput:quote.minimumOutput!});
 const exact={...buy,amountMode:"tokens" as const,amount:"10000"};
 quote=await service.quote(exact);const before=await client.getBalance({address});
 const receipt=await service.trade({...exact,quoteId:quote.id,minimumOutput:quote.minimumOutput!});
 const after=await client.getBalance({address});
 assert.equal(before-after-receipt.gasUsed*receipt.effectiveGasPrice,parseEther(quote.paymentAmount!));
 await assert.rejects(()=>service.trade({...exact,quoteId:quote.id,minimumOutput:quote.minimumOutput!}),/expired/);
 const held=await client.readContract({address:market.token.id as Address,abi:memeAbi,functionName:"balanceOf",args:[address]});
 const amount=formatUnits(held/2n,18);
 await service.approve(market.token.id as Address,router,amount);
 const sell={...buy,side:"sell" as const,amount};quote=await service.quote(sell);
 await service.trade({...sell,quoteId:quote.id,minimumOutput:quote.minimumOutput!});
 assert.equal(await client.readContract({address:asset.id,abi:stockAbi,functionName:"balanceOf",args:[address]}),0n);
 await service.launchCurveWithMON({name:"MON first buy",symbol:"MONFIRST",stockTokenId:asset.id,devBuyAmount:"100",tradingFeeBps:100,paymentAsset:"native",metadata:{website:"https://example.com"}});
 const first=(await service.snapshot(address)).markets.find(m=>m.token.symbol==="MONFIRST")!;
 assert.ok(parseEther(first.walletBalance!)>0n);
 assert.equal(await client.readContract({address:router,abi:nativeRouterAbi,functionName:"creatorOf",args:[first.token.id as Address]}),address);
 assert.equal(await client.readContract({address:asset.id,abi:stockAbi,functionName:"allowance",args:[address,router]}),0n);
 console.log("PASS: zero quote balance, MON buy, exact-token buy/refund, MON sell, native launch/dev buy and creator attribution.");
}
